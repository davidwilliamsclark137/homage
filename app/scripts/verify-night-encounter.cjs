assert(!JSON.stringify(a).includes(key(4)),'Never expose peer credential');
assert.equal(act(1,'collect',{step:0,portalId:'patina-storefront',arrived:true}).status,409);
assert.equal(collect(1,0).body.progress,1);
assert.equal(collect(1,0).body.progress,1,'Retrying a collection is idempotent');
